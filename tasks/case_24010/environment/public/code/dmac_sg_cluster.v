`timescale 1ns/100ps

module dmac_sg_cluster #(
  parameter DMA_DATA_WIDTH_SRC = 64,
  parameter DMA_DATA_WIDTH_DEST = 64,
  parameter DMA_AXI_ADDR_WIDTH = 32,
  parameter DMA_LENGTH_WIDTH = 16,
  parameter MAX_BYTES_PER_BURST = 32,
  parameter BYTES_PER_BURST_WIDTH = 5,
  parameter FIFO_SIZE = 4
) (
  input  wire                               req_clk,
  input  wire                               req_resetn,
  input  wire                               req_enable,
  input  wire                               sg_enable,
  input  wire                               src_enable,
  input  wire                               dest_enable,

  input  wire                               desc_req_valid,
  output wire                               desc_req_ready,
  input  wire [DMA_AXI_ADDR_WIDTH-1:3]      desc_req_address,
  input  wire                               desc_sync_start,

  output wire                               xfer_eot,
  output wire [31:0]                        xfer_desc_id,
  output wire                               xfer_eot_irq,
  output wire [BYTES_PER_BURST_WIDTH-1:0]   xfer_measured_len,
  output wire                               xfer_partial,
  output wire                               xfer_resp_valid,
  input  wire                               xfer_resp_ready,

  // Scatter-Gather Descriptor Read AXI4 Master
  input  wire                               m_sg_axi_aclk,
  input  wire                               m_sg_axi_aresetn,
  input  wire                               m_sg_axi_arready,
  output wire                               m_sg_axi_arvalid,
  output wire [DMA_AXI_ADDR_WIDTH-1:0]      m_sg_axi_araddr,
  output wire [7:0]                         m_sg_axi_arlen,
  output wire [2:0]                         m_sg_axi_arsize,
  output wire [1:0]                         m_sg_axi_arburst,
  input  wire [63:0]                        m_sg_axi_rdata,
  input  wire                               m_sg_axi_rlast,
  output wire                               m_sg_axi_rready,
  input  wire                               m_sg_axi_rvalid,
  input  wire [1:0]                         m_sg_axi_rresp,

  // Source AXI4-Stream Slave
  input  wire                               s_axis_aclk,
  input  wire                               s_axis_aresetn,
  output wire                               s_axis_ready,
  input  wire                               s_axis_valid,
  input  wire [DMA_DATA_WIDTH_SRC-1:0]      s_axis_data,
  input  wire                               s_axis_last,
  input  wire [0:0]                         s_axis_user,
  output wire                               s_axis_xfer_req,

  // Destination AXI4 Memory-Mapped Write Master
  input  wire                               m_dest_axi_aclk,
  input  wire                               m_dest_axi_aresetn,
  output wire [DMA_AXI_ADDR_WIDTH-1:0]      m_axi_awaddr,
  output wire [7:0]                         m_axi_awlen,
  output wire [2:0]                         m_axi_awsize,
  output wire [1:0]                         m_axi_awburst,
  output wire                               m_axi_awvalid,
  input  wire                               m_axi_awready,
  output wire [DMA_DATA_WIDTH_DEST-1:0]     m_axi_wdata,
  output wire [(DMA_DATA_WIDTH_DEST/8)-1:0] m_axi_wstrb,
  input  wire                               m_axi_wready,
  output wire                               m_axi_wvalid,
  output wire                               m_axi_wlast,
  input  wire                               m_axi_bvalid,
  input  wire [1:0]                         m_axi_bresp,
  output wire                               m_axi_bready
);

  localparam BYTES_PER_BEAT_SRC  = $clog2(DMA_DATA_WIDTH_SRC/8);
  localparam BYTES_PER_BEAT_DEST = $clog2(DMA_DATA_WIDTH_DEST/8);

  wire sg_req_valid;
  wire sg_req_ready;
  wire [DMA_AXI_ADDR_WIDTH-1:BYTES_PER_BEAT_DEST] sg_dest_addr;
  wire [DMA_AXI_ADDR_WIDTH-1:BYTES_PER_BEAT_SRC]  sg_src_addr;
  wire [DMA_LENGTH_WIDTH-1:0] sg_x_len;
  wire [DMA_LENGTH_WIDTH-1:0] sg_y_len;
  wire [DMA_LENGTH_WIDTH-1:0] sg_d_str;
  wire [DMA_LENGTH_WIDTH-1:0] sg_s_str;

  dmac_sg #(
    .DMA_AXI_ADDR_WIDTH(DMA_AXI_ADDR_WIDTH),
    .DMA_DATA_WIDTH(64),
    .DMA_LENGTH_WIDTH(DMA_LENGTH_WIDTH),
    .AXI_LENGTH_WIDTH(8),
    .BYTES_PER_BEAT_WIDTH_DEST(BYTES_PER_BEAT_DEST),
    .BYTES_PER_BEAT_WIDTH_SRC(BYTES_PER_BEAT_SRC),
    .BYTES_PER_BEAT_WIDTH_SG(3),
    .ASYNC_CLK_REQ_SG(1)
  ) u_sg (
    .req_clk(req_clk),
    .req_resetn(req_resetn),
    .req_enable(req_enable),
    .sg_clk(),
    .sg_resetn(m_sg_axi_aresetn),
    .sg_ext_resetn(),
    .sg_enable(sg_enable),
    .sg_enabled(),
    .req_in_valid(desc_req_valid),
    .req_in_ready(desc_req_ready),
    .req_out_valid(sg_req_valid),
    .req_out_ready(sg_req_ready),
    .resp_out_eot(xfer_eot_irq),
    .resp_in_valid(xfer_resp_valid & xfer_resp_ready & xfer_eot),
    .req_desc_address(desc_req_address),
    .out_dest_address(sg_dest_addr),
    .out_src_address(sg_src_addr),
    .out_x_length(sg_x_len),
    .out_y_length(sg_y_len),
    .out_dest_stride(sg_d_str),
    .out_src_stride(sg_s_str),
    .resp_out_id(xfer_desc_id),
    .m_axi_aclk(m_sg_axi_aclk),
    .m_axi_aresetn(m_sg_axi_aresetn),
    .m_axi_arready(m_sg_axi_arready),
    .m_axi_arvalid(m_sg_axi_arvalid),
    .m_axi_araddr(m_sg_axi_araddr),
    .m_axi_arlen(m_sg_axi_arlen),
    .m_axi_arsize(m_sg_axi_arsize),
    .m_axi_arburst(m_axi_arburst),
    .m_axi_arprot(),
    .m_axi_arcache(),
    .m_axi_rdata(m_sg_axi_rdata),
    .m_axi_rlast(m_sg_axi_rlast),
    .m_axi_rready(m_sg_axi_rready),
    .m_axi_rvalid(m_sg_axi_rvalid),
    .m_axi_rresp(m_sg_axi_rresp)
  );

  request_arb #(
    .DMA_DATA_WIDTH_SRC(DMA_DATA_WIDTH_SRC),
    .DMA_DATA_WIDTH_DEST(DMA_DATA_WIDTH_DEST),
    .DMA_LENGTH_WIDTH(DMA_LENGTH_WIDTH),
    .DMA_LENGTH_ALIGN(BYTES_PER_BEAT_SRC),
    .BYTES_PER_BEAT_WIDTH_DEST(BYTES_PER_BEAT_DEST),
    .BYTES_PER_BEAT_WIDTH_SRC(BYTES_PER_BEAT_SRC),
    .DMA_TYPE_DEST(0),
    .DMA_TYPE_SRC(1),
    .DMA_AXI_ADDR_WIDTH(DMA_AXI_ADDR_WIDTH),
    .ASYNC_CLK_REQ_SRC(1),
    .ASYNC_CLK_SRC_DEST(1),
    .ASYNC_CLK_DEST_REQ(1),
    .AXIS_TUSER_SYNC(1),
    .MAX_BYTES_PER_BURST(MAX_BYTES_PER_BURST),
    .BYTES_PER_BURST_WIDTH(BYTES_PER_BURST_WIDTH),
    .FIFO_SIZE(FIFO_SIZE),
    .ALLOW_ASYM_MEM(1),
    .USE_EXT_SYNC(0)
  ) u_arb (
    .req_clk(req_clk),
    .req_resetn(req_resetn),
    .req_valid(sg_req_valid),
    .req_ready(sg_req_ready),
    .req_dest_address(sg_dest_addr),
    .req_src_address(sg_src_addr),
    .req_length(sg_x_len),
    .req_xlast(1'b1),
    .req_islast(1'b1),
    .req_sync_transfer_start(desc_sync_start),
    .req_sync(1'b1),
    .eot(xfer_eot),
    .measured_burst_length(xfer_measured_len),
    .response_partial(xfer_partial),
    .response_valid(xfer_resp_valid),
    .response_ready(xfer_resp_ready),
    .abort_req(),
    .m_dest_axi_aclk(m_dest_axi_aclk),
    .m_dest_axi_aresetn(m_dest_axi_aresetn),
    .m_src_axi_aclk(1'b0),
    .m_src_axi_aresetn(1'b1),
    .m_axi_awaddr(m_axi_awaddr),
    .m_axi_awlen(m_axi_awlen),
    .m_axi_awsize(m_axi_awsize),
    .m_axi_awburst(m_axi_awburst),
    .m_axi_awprot(),
    .m_axi_awcache(),
    .m_axi_awvalid(m_axi_awvalid),
    .m_axi_awready(m_axi_awready),
    .m_axi_wdata(m_axi_wdata),
    .m_axi_wstrb(m_axi_wstrb),
    .m_axi_wready(m_axi_wready),
    .m_axi_wvalid(m_axi_wvalid),
    .m_axi_wlast(m_axi_wlast),
    .m_axi_bvalid(m_axi_bvalid),
    .m_axi_bresp(m_axi_bresp),
    .m_axi_bready(m_axi_bready),
    .m_axi_arready(1'b0),
    .m_axi_arvalid(),
    .m_axi_araddr(),
    .m_axi_arlen(),
    .m_axi_arsize(),
    .m_axi_arburst(),
    .m_axi_arprot(),
    .m_axi_arcache(),
    .m_axi_rdata({DMA_DATA_WIDTH_SRC{1'b0}}),
    .m_axi_rready(),
    .m_axi_rvalid(1'b0),
    .m_axi_rlast(1'b0),
    .m_axi_rresp(2'b00),
    .s_axis_aclk(s_axis_aclk),
    .s_axis_ready(s_axis_ready),
    .s_axis_valid(s_axis_valid),
    .s_axis_data(s_axis_data),
    .s_axis_last(s_axis_last),
    .s_axis_user(s_axis_user),
    .s_axis_xfer_req(s_axis_xfer_req),
    .m_axis_aclk(1'b0),
    .m_axis_ready(1'b1),
    .m_axis_valid(),
    .m_axis_data(),
    .m_axis_user(),
    .m_axis_last(),
    .m_axis_xfer_req(),
    .fifo_wr_clk(1'b0),
    .fifo_wr_en(1'b0),
    .fifo_wr_din({DMA_DATA_WIDTH_SRC{1'b0}}),
    .fifo_wr_overflow(),
    .fifo_wr_xfer_req(),
    .fifo_rd_clk(1'b0),
    .fifo_rd_en(1'b0),
    .fifo_rd_valid(),
    .fifo_rd_dout(),
    .fifo_rd_underflow(),
    .fifo_rd_xfer_req(),
    .dbg_dest_request_id(),
    .dbg_dest_address_id(),
    .dbg_dest_data_id(),
    .dbg_dest_response_id(),
    .dbg_src_request_id(),
    .dbg_src_address_id(),
    .dbg_src_data_id(),
    .dbg_src_response_id(),
    .req_enable(req_enable),
    .dest_clk(),
    .dest_resetn(m_dest_axi_aresetn),
    .dest_ext_resetn(),
    .dest_enable(dest_enable),
    .dest_enabled(),
    .src_clk(),
    .src_resetn(s_axis_aresetn),
    .src_ext_resetn(),
    .src_enable(src_enable),
    .src_enabled(),
    .src_ext_sync(1'b0),
    .dest_ext_sync(1'b0),
    .ext_sync_ready(),
    .ext_sync_valid(1'b1),
    .dest_diag_level_bursts()
  );

endmodule
