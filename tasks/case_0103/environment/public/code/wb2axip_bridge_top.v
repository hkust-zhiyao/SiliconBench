////////////////////////////////////////////////////////////////////////////////
//
// Coupled WB2AXIP Bridge Subsystem Top Wrapper (`wb2axip_bridge_top`)
// Integrates:
//   1. `wbm2axisp` (32-bit Wishbone B4 master to 64-bit AXI4 master bridge)
//   2. `axim2wbsp` -> `aximwr2wbsp` + `aximrd2wbsp` + `wbarbiter`
//      (32-bit AXI4 write/read slave to pipelined Wishbone B4 master bridge)
//
////////////////////////////////////////////////////////////////////////////////
`default_nettype none

module wb2axip_bridge_top #(
    parameter C_AXI_ID_WIDTH   = 6,
    parameter C_AXI_ADDR_WIDTH = 16,
    parameter LGFIFO           = 3
) (
    input  wire                        i_clk,
    input  wire                        i_reset,

    // -------------------------------------------------------------------------
    // Subsystem A: `wbm2axisp` (32-bit Wishbone slave -> 64-bit AXI4 master)
    // -------------------------------------------------------------------------
    input  wire                        wb_up_cyc,
    input  wire                        wb_up_stb,
    input  wire                        wb_up_we,
    input  wire [13:0]                 wb_up_addr,
    input  wire [31:0]                 wb_up_data,
    input  wire [3:0]                  wb_up_sel,
    output wire                        wb_up_stall,
    output wire                        wb_up_ack,
    output wire [31:0]                 wb_up_rdata,
    output wire                        wb_up_err,

    output wire                        m_axi_awvalid,
    input  wire                        m_axi_awready,
    output wire [C_AXI_ID_WIDTH-1:0]   m_axi_awid,
    output wire [C_AXI_ADDR_WIDTH-1:0] m_axi_awaddr,
    output wire                        m_axi_wvalid,
    input  wire                        m_axi_wready,
    output wire [63:0]                 m_axi_wdata,
    output wire [7:0]                  m_axi_wstrb,
    output wire                        m_axi_wlast,
    input  wire                        m_axi_bvalid,
    output wire                        m_axi_bready,
    input  wire [C_AXI_ID_WIDTH-1:0]   m_axi_bid,
    input  wire [1:0]                  m_axi_bresp,
    output wire                        m_axi_arvalid,
    input  wire                        m_axi_arready,
    output wire [C_AXI_ID_WIDTH-1:0]   m_axi_arid,
    output wire [C_AXI_ADDR_WIDTH-1:0] m_axi_araddr,
    input  wire                        m_axi_rvalid,
    output wire                        m_axi_rready,
    input  wire [C_AXI_ID_WIDTH-1:0]   m_axi_rid,
    input  wire [63:0]                 m_axi_rdata,
    input  wire [1:0]                  m_axi_rresp,
    input  wire                        m_axi_rlast,

    // -------------------------------------------------------------------------
    // Subsystem B: `axim2wbsp` (`aximwr2wbsp` + `aximrd2wbsp` -> 32-bit WB)
    // -------------------------------------------------------------------------
    input  wire                        s_axi_awvalid,
    output wire                        s_axi_awready,
    input  wire [C_AXI_ID_WIDTH-1:0]   s_axi_awid,
    input  wire [C_AXI_ADDR_WIDTH-1:0] s_axi_awaddr,
    input  wire [7:0]                  s_axi_awlen,
    input  wire [2:0]                  s_axi_awsize,
    input  wire [1:0]                  s_axi_awburst,
    input  wire                        s_axi_wvalid,
    output wire                        s_axi_wready,
    input  wire [31:0]                 s_axi_wdata,
    input  wire [3:0]                  s_axi_wstrb,
    input  wire                        s_axi_wlast,
    output wire                        s_axi_bvalid,
    input  wire                        s_axi_bready,
    output wire [C_AXI_ID_WIDTH-1:0]   s_axi_bid,
    output wire [1:0]                  s_axi_bresp,

    input  wire                        s_axi_arvalid,
    output wire                        s_axi_arready,
    input  wire [C_AXI_ID_WIDTH-1:0]   s_axi_arid,
    input  wire [C_AXI_ADDR_WIDTH-1:0] s_axi_araddr,
    input  wire [7:0]                  s_axi_arlen,
    input  wire [2:0]                  s_axi_arsize,
    input  wire [1:0]                  s_axi_arburst,
    output wire                        s_axi_rvalid,
    input  wire                        s_axi_rready,
    output wire [C_AXI_ID_WIDTH-1:0]   s_axi_rid,
    output wire [31:0]                 s_axi_rdata,
    output wire                        s_axi_rlast,
    output wire [1:0]                  s_axi_rresp,

    output wire                        wb_dn_cyc,
    output wire                        wb_dn_stb,
    output wire                        wb_dn_we,
    output wire [13:0]                 wb_dn_addr,
    output wire [31:0]                 wb_dn_wdata,
    output wire [3:0]                  wb_dn_sel,
    input  wire                        wb_dn_stall,
    input  wire                        wb_dn_ack,
    input  wire [31:0]                 wb_dn_rdata,
    input  wire                        wb_dn_err
);

    wbm2axisp #(
        .C_AXI_DATA_WIDTH(64),
        .C_AXI_ADDR_WIDTH(C_AXI_ADDR_WIDTH),
        .C_AXI_ID_WIDTH  (C_AXI_ID_WIDTH),
        .DW              (32),
        .AW              (14),
        .AXI_WRITE_ID    (6'h05),
        .AXI_READ_ID     (6'h1A),
        .OPT_LITTLE_ENDIAN(1'b1),
        .LGFIFO          (LGFIFO)
    ) u_wbm2axi (
        .i_clk        (i_clk),
        .i_reset      (i_reset),
        .o_axi_awvalid(m_axi_awvalid),
        .i_axi_awready(m_axi_awready),
        .o_axi_awid   (m_axi_awid),
        .o_axi_awaddr (m_axi_awaddr),
        .o_axi_awlen  (),
        .o_axi_awsize (),
        .o_axi_awburst(),
        .o_axi_awlock (),
        .o_axi_awcache(),
        .o_axi_awprot (),
        .o_axi_awqos  (),
        .o_axi_wvalid (m_axi_wvalid),
        .i_axi_wready (m_axi_wready),
        .o_axi_wdata  (m_axi_wdata),
        .o_axi_wstrb  (m_axi_wstrb),
        .o_axi_wlast  (m_axi_wlast),
        .i_axi_bvalid (m_axi_bvalid),
        .o_axi_bready (m_axi_bready),
        .i_axi_bid    (m_axi_bid),
        .i_axi_bresp  (m_axi_bresp),
        .o_axi_arvalid(m_axi_arvalid),
        .i_axi_arready(m_axi_arready),
        .o_axi_arid   (m_axi_arid),
        .o_axi_araddr (m_axi_araddr),
        .o_axi_arlen  (),
        .o_axi_arsize (),
        .o_axi_arburst(),
        .o_axi_arlock (),
        .o_axi_arcache(),
        .o_axi_arprot (),
        .o_axi_arqos  (),
        .i_axi_rvalid (m_axi_rvalid),
        .o_axi_rready (m_axi_rready),
        .i_axi_rid    (m_axi_rid),
        .i_axi_rdata  (m_axi_rdata),
        .i_axi_rresp  (m_axi_rresp),
        .i_axi_rlast  (m_axi_rlast),
        .i_wb_cyc     (wb_up_cyc),
        .i_wb_stb     (wb_up_stb),
        .i_wb_we      (wb_up_we),
        .i_wb_addr    (wb_up_addr),
        .i_wb_data    (wb_up_data),
        .i_wb_sel     (wb_up_sel),
        .o_wb_stall   (wb_up_stall),
        .o_wb_ack     (wb_up_ack),
        .o_wb_data    (wb_up_rdata),
        .o_wb_err     (wb_up_err)
    );

    axim2wbsp #(
        .C_AXI_ID_WIDTH  (C_AXI_ID_WIDTH),
        .C_AXI_DATA_WIDTH(32),
        .C_AXI_ADDR_WIDTH(C_AXI_ADDR_WIDTH),
        .LGFIFO          (LGFIFO)
    ) u_axi2wbm (
        .S_AXI_ACLK   (i_clk),
        .S_AXI_ARESETN(!i_reset),
        .S_AXI_AWVALID(s_axi_awvalid),
        .S_AXI_AWREADY(s_axi_awready),
        .S_AXI_AWID   (s_axi_awid),
        .S_AXI_AWADDR (s_axi_awaddr),
        .S_AXI_AWLEN  (s_axi_awlen),
        .S_AXI_AWSIZE (s_axi_awsize),
        .S_AXI_AWBURST(s_axi_awburst),
        .S_AXI_AWLOCK (1'b0),
        .S_AXI_AWCACHE(4'h0),
        .S_AXI_AWPROT (3'h0),
        .S_AXI_AWQOS  (4'h0),
        .S_AXI_WVALID (s_axi_wvalid),
        .S_AXI_WREADY (s_axi_wready),
        .S_AXI_WDATA  (s_axi_wdata),
        .S_AXI_WSTRB  (s_axi_wstrb),
        .S_AXI_WLAST  (s_axi_wlast),
        .S_AXI_BVALID (s_axi_bvalid),
        .S_AXI_BREADY (s_axi_bready),
        .S_AXI_BID    (s_axi_bid),
        .S_AXI_BRESP  (s_axi_bresp),
        .S_AXI_ARVALID(s_axi_arvalid),
        .S_AXI_ARREADY(s_axi_arready),
        .S_AXI_ARID   (s_axi_arid),
        .S_AXI_ARADDR (s_axi_araddr),
        .S_AXI_ARLEN  (s_axi_arlen),
        .S_AXI_ARSIZE (s_axi_arsize),
        .S_AXI_ARBURST(s_axi_arburst),
        .S_AXI_ARLOCK (1'b0),
        .S_AXI_ARCACHE(4'h0),
        .S_AXI_ARPROT (3'h0),
        .S_AXI_ARQOS  (4'h0),
        .S_AXI_RVALID (s_axi_rvalid),
        .S_AXI_RREADY (s_axi_rready),
        .S_AXI_RID    (s_axi_rid),
        .S_AXI_RDATA  (s_axi_rdata),
        .S_AXI_RLAST  (s_axi_rlast),
        .S_AXI_RRESP  (s_axi_rresp),
        .o_reset      (),
        .o_wb_cyc     (wb_dn_cyc),
        .o_wb_stb     (wb_dn_stb),
        .o_wb_we      (wb_dn_we),
        .o_wb_addr    (wb_dn_addr),
        .o_wb_data    (wb_dn_wdata),
        .o_wb_sel     (wb_dn_sel),
        .i_wb_stall   (wb_dn_stall),
        .i_wb_ack     (wb_dn_ack),
        .i_wb_data    (wb_dn_rdata),
        .i_wb_err     (wb_dn_err)
    );

endmodule
`default_nettype wire
